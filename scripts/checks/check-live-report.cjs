const workDir=require('node:path').resolve(__dirname,'../../work');require('node:fs').mkdirSync(workDir,{recursive:true});
const { _electron: electron } = require('./lib/playwright.cjs');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname,'../..');
(async () => {
 const { Workroom } = await import(pathToFileURL(path.join(root, 'src/core/service.mjs')));
 const { Client } = await import('@modelcontextprotocol/sdk/client/index.js');
 const { StdioClientTransport } = await import('@modelcontextprotocol/sdk/client/stdio.js');
 const dir = fs.mkdtempSync(path.join(workDir, 'live-report-'));
 const room = new Workroom(path.join(dir, 'workroom.sqlite'));
 const p = await room.createProduct({ name: '작업실', folder: root, goal: '보고에서 초안까지 자동 연결' });
 const env = { ...process.env, WORKROOM_DATA_DIR: dir, WORKROOM_HEADLESS: '0' }; delete env.ELECTRON_RUN_AS_NODE;
 const client = new Client({ name: 'live-report-review', version: '1.0' });
 const transport = new StdioClientTransport({ command: process.execPath, args: [path.join(root, 'src/mcp/server.mjs')], env, stderr: 'pipe' });
 const app = await electron.launch({ executablePath: require('electron'), args: [root], env });
 let page; const checks = [], errors = [];
 try {
  await client.connect(transport); page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message));
  const click = name => page.getByRole('button', { name, exact: true }).click();
  const report = async (externalId, sourceVersion = 1, extra = {}) => {
   const response = await client.callTool({ name: 'workroom_report_work', arguments: { productId: p.id, externalId, sourceVersion, title: externalId === 'input' ? '입력 소실 수정' : externalId, summary: '미저장 입력을 보호하도록 수정했습니다.', evidence: '격리된 UI 연동 검증 자료', limitations: '실제 제품 검사의 증명이 아닙니다.', contribution: '사용자 문제 제기 · 에이전트 구현', changedFiles: [{ path: 'src/renderer/app.js', summary: '입력 보존' }], checks: [{ name: '입력 보호', result: 'passed', detail: '검증용 보고' }], ...extra } });
   assert.ok(!response.isError, response.content[0].text); return JSON.parse(response.content[0].text);
  };
  await click('포트폴리오'); await click('첫 대상 추가');
  await page.getByLabel('기업 또는 대상 이름').fill('개발 도구 기업');
  await page.getByRole('checkbox', { name: '작업실의 새 작업을 이 초안에 자동 반영' }).check();
  await click('초안 만들기'); await page.getByLabel('페이지 첫 문장').fill('개발 흐름을 개선하는 도구를 만듭니다.'); await click('초안 저장');
  const task = await report('input');
  await page.locator('.paper h3').filter({ hasText: '입력 소실 수정' }).waitFor({ timeout: 8000 });
  assert.equal(room.snapshot().portfolios[0].entries.length, 1); checks.push('real MCP report appears in subscribed draft without refresh');
  const token = room.changes(); await report('input'); assert.equal(room.changes(), token); assert.equal(room.snapshot().tasks.length, 1); checks.push('MCP retry creates no duplicate');
  await click('초안 편집'); await page.getByLabel('사례 설명', { exact: true }).fill('직접 다듬은 지원용 문장');
  await report('추가 검사 기록'); await report('input', 2, { title: '입력 보호 재검사', summary: '외부에서 보완한 설명' });
  await page.locator('.sync-notice').filter({ hasText: '새 기록이 도착' }).waitFor({ timeout: 8000 });
  assert.equal(await page.getByLabel('사례 설명', { exact: true }).inputValue(), '직접 다듬은 지원용 문장');
  await click('초안 저장'); assert.match(await page.locator('.paper').innerText(), /직접 다듬은 지원용 문장/);
  assert.match(await page.locator('.paper').innerText(), /추가 검사 기록/); assert.match(await page.locator('.paper').innerText(), /입력 보호 재검사/);
  checks.push('incoming reports merge with unsaved edits, preserving manual text');
  await click('초안 편집'); await page.getByLabel('페이지 첫 문장').fill('내가 작성 중인 소개');
  let f = room.snapshot().portfolios[0]; room.savePortfolio({ id: f.id, revision: f.revision, intro: '다른 창에서 저장한 소개', requirements: f.requirements, entries: f.entries });
  await click('초안 저장'); await page.getByRole('heading', { name: '저장된 초안에 다른 변경이 있습니다' }).waitFor();
  assert.equal(await page.getByLabel('페이지 첫 문장').inputValue(), '내가 작성 중인 소개');
  await page.locator('.conflict-review summary').click();
  await page.screenshot({ path: path.join(root, 'outputs/app-report-conflict.png'), scale: 'css' });
  await click('내 변경 우선으로 저장'); assert.match(await page.locator('.paper').innerText(), /내가 작성 중인 소개/); checks.push('concurrent manual conflict preserves input and requires explicit resolution');
  await click('HTML 내보내기 검토');
  f = room.snapshot().portfolios[0]; room.savePortfolio({ id: f.id, revision: f.revision, intro: '검토 중 바뀐 소개', requirements: f.requirements, entries: f.entries });
  await page.locator('.sync-notice').filter({ hasText: '검토 중인 내용은 유지' }).waitFor({ timeout: 8000 });
  assert.match(await page.locator('.dialog .paper').innerText(), /내가 작성 중인 소개/);
  await click('HTML 파일로 저장'); await page.getByText('초안이 변경되었습니다.', { exact: false }).waitFor();
  assert.equal(room.snapshot().portfolios[0].exports.length, 0);
  await click('편집으로 돌아가기'); await page.locator('.paper h2').filter({ hasText: '검토 중 바뀐 소개' }).waitFor({ timeout: 8000 });
  checks.push('export review freezes displayed content and blocks exporting a changed revision');
  await click('초안 편집'); await page.locator('.entry-editor').filter({ has: page.getByRole('heading', { name: '입력 보호 재검사', exact: true }) }).getByRole('button', { name: '제외', exact: true }).click();
  await click('초안 저장'); await report('input', 3, { title: '제외한 작업의 수정 보고' });
  await page.locator('.tasknav').getByText('제외한 작업의 수정 보고', { exact: true }).waitFor({ timeout: 8000 });
  assert.ok(!(await page.locator('.paper').innerText()).includes('제외한 작업'));
  assert.ok(!room.snapshot().portfolios[0].entries.some(e => e.taskId === task.id)); checks.push('excluded case stays excluded on a newer report');
  await click('초안 편집'); await page.locator('.subscriptions summary').click(); await page.locator('.subscriptions').getByRole('checkbox', { name: '작업실', exact: true }).uncheck(); await click('초안 저장');
  await report('반영 중단 뒤 작업'); await page.locator('.tasknav').getByText('반영 중단 뒤 작업', { exact: true }).waitFor({ timeout: 8000 });
  assert.equal(room.snapshot().portfolios[0].entries.length, 1); checks.push('stopping subscription preserves existing cases and stops future inclusion');
  await page.screenshot({ path: path.join(root, 'outputs/app-report-flow.png'), scale: 'css' });
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(workDir, 'live-report-check.json'), JSON.stringify({ passed: true, checks, errors, dataDirectory: dir }, null, 2));
  console.log(JSON.stringify({ passed: true, checks }));
 } catch (error) { if (page) { await page.screenshot({ path: path.join(workDir, 'live-report-failure.png'), scale: 'css' }).catch(() => {}); console.error((await page.locator('main').innerText()).slice(0, 2500)); } throw error;
 } finally { await client.close(); await app.close(); room.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
